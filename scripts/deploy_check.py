"""`make deploy-check`: validate the hosted (Vercel) configuration WITHOUT deploying anything (ADR-0013).

Checks, in order (any failure exits non-zero):
1. vercel.json parses and points maxDuration (≤ 300 s, the Hobby limit) and excludeFiles at app.py.
2. requirements.txt matches backend/uv.lock (runtime groups only) — generated by scripts/export-requirements.sh.
3. The root entrypoint `app.py` imports and serves in hosted mode, using a throwaway LOCAL libSQL file in place of
   the remote database and a random access token: /api/health over the public host, the built UI at /, the host
   allowlist (a Vercel deployment URL is refused), HSTS, and a Secure session cookie on login.
No network is used; nothing is written outside a temporary directory.
"""

from __future__ import annotations

import json
import os
import runpy
import secrets
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORIGIN = "https://iip-deploy-check.example.test"


def fail(msg: str) -> None:
    print(f"deploy-check: FAIL — {msg}", file=sys.stderr)
    raise SystemExit(1)


def check_vercel_json() -> None:
    cfg = json.loads((ROOT / "vercel.json").read_text())
    fn = cfg.get("functions", {}).get("app.py")
    if not fn:
        fail("vercel.json has no functions entry for app.py")
    if not 0 < int(fn.get("maxDuration", 0)) <= 300:
        fail("functions.app.py.maxDuration must be within the Hobby limit (1-300 s)")
    if "backend/tests/**" not in fn.get("excludeFiles", ""):
        fail("excludeFiles must keep tests out of the function bundle")
    print("deploy-check: vercel.json OK")


def check_requirements() -> None:
    fresh = subprocess.run([str(ROOT / "scripts" / "export-requirements.sh")], capture_output=True, text=True,
                           check=True).stdout  # fmt: skip
    if fresh != (ROOT / "requirements.txt").read_text():
        fail("requirements.txt is out of date with backend/uv.lock: run `make requirements`")
    print("deploy-check: requirements.txt in sync with uv.lock")


def check_entrypoint() -> None:
    if not (ROOT / "frontend" / "dist" / "index.html").exists():
        fail("frontend/dist missing: run `make build` first")
    with tempfile.TemporaryDirectory() as tmp:
        token = secrets.token_urlsafe(32)
        os.environ.update({
            "IIP_DEPLOY": "vercel", "IIP_ENV": "test", "IIP_PUBLIC_ORIGIN": ORIGIN,
            "IIP_DB_URL": str(Path(tmp) / "hosted.db"), "IIP_ACCESS_TOKEN": token, "IIP_LLM": "off",
        })  # fmt: skip
        os.environ.pop("IIP_DB_AUTH_TOKEN", None)
        sys.path.insert(0, str(ROOT / "backend" / "src"))
        from fastapi.testclient import TestClient  # noqa: PLC0415

        app = runpy.run_path(str(ROOT / "app.py"))["app"]
        with TestClient(app, base_url=ORIGIN) as c:
            if c.get("/api/health").status_code != 200:
                fail("/api/health did not answer 200 on the public host")
            home = c.get("/")
            if home.status_code != 200 or "<html" not in home.text.lower():
                fail("the built UI is not served at /")
            if "strict-transport-security" not in home.headers:
                fail("HSTS header missing in hosted mode")
            other = c.get("/api/health", headers={"host": "iip-abc123.vercel.app"})
            if other.status_code != 400:
                fail("a non-public host was not refused")
            login = c.post("/api/session", json={"token": token}, headers={"Origin": ORIGIN})
            cookie = login.headers.get("set-cookie", "")
            if login.status_code != 200 or "secure" not in cookie.lower() or "samesite=strict" not in cookie.lower():
                fail("login did not set a Secure, SameSite=Strict session cookie")
    print("deploy-check: hosted entrypoint OK (health, UI, host allowlist, HSTS, Secure cookie)")


def main() -> None:
    check_vercel_json()
    check_requirements()
    check_entrypoint()
    print("deploy-check: all checks passed (nothing was deployed)")


if __name__ == "__main__":
    main()
