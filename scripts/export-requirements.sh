#!/usr/bin/env bash
# Print the hosted (Vercel) runtime requirements, generated from backend/uv.lock (ADR-0013).
# Runtime dependencies only: no dev group, no oracle group (QuantLib etc. are test oracles, never imported by src/).
set -euo pipefail
cd "$(dirname "$0")/../backend"
echo "# GENERATED by \`make requirements\` from backend/uv.lock (runtime dependencies only; no dev or oracle groups)."
echo "# Used ONLY by the hosted (Vercel) deployment, ADR-0013. Do not edit by hand; \`make deploy-check\` checks it."
uv export --frozen --no-dev --no-group oracle --no-hashes --no-emit-project --format requirements-txt \
  | grep -v '^ *#'
